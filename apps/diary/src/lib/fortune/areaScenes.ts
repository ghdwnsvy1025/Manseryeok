export type AreaSceneNote = { 좋은: string } | { 조심: string };
/** 오늘 신호 있는 영역의 장면 한 줄. 그 영역을 그 방향으로 움직인 가장 센 글자의 십신으로 고른다(이유 문구와 같은 글자). 가족이나 신호 없음이면 null */
export function areaScene(area: AreaName, e: AreaProfileEntry): AreaSceneNote | null {
  const scene = SCENE_AREA[area];
  const top = scene ? strongestContribution(e) : null;
  if (!scene || !top) return null;
  const pair = AREA_SCENE[scene][top.tenGod as TenGod];
  if (!pair) return null;
  return e.strength > 0 ? { 좋은: pair.좋은 } : { 조심: pair.조심 };
}
