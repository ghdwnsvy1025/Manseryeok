/** v4.16 판단 — 글보다 먼저 정하는 것. 화면에는 안 나가고 캐시에 남는다 */
export interface FortuneJudge { 후보: string[]; 핵심: string; 이유: string; 구조: Structure; 둘째기운: string; 운맥락: string }

