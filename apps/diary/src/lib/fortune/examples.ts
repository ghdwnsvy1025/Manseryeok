//   구조(A~E)가 서로 다르고, 판단(후보 → 핵심)과 태그(의미 중복 검사용)를 글보다 먼저 적는다. 세 편 모두 검사기를 통과한다(테스트).
export type BlockKind = "근거" | "원리" | "성향" | "사례" | "처방";
export interface FortuneBlock { kind: BlockKind; text: string }
/** v4.15 블록 → 본문 (옛 테스트·검사기 호환용) */
export function joinBlocks(blocks: readonly FortuneBlock[]): string {
  const texts = blocks.map((b) => String(b?.text ?? "").trim()).filter(Boolean);
  if (texts.length <= 2) return texts.join(" ");
  const cut = Math.ceil(texts.length / 2);
  return `${texts.slice(0, cut).join(" ")}\n\n${texts.slice(cut).join(" ")}`;
}

/** v4.16 구조: A 핵심→상황→조언 · B 사례→성향→조언 · C 감정→모습→조언 · D 주의 상황→이유→해결 · E 잘 되는 것→활용→주의점 */
export type Structure = "A" | "B" | "C" | "D" | "E";
/** v4.16 의미 태그 — 최근 7일(제목뜻은 14일)과 비교하는 뜻의 요약. 짧은 명사구 */
export interface FortuneTags { 주제: string; 감정: string; 상황: string; 영역: string; 장면: string; 권장: string; 피할: string; 제목뜻: string }
