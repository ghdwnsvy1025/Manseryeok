/** 날짜로 하나 고르기 — 템플릿·brief가 같은 규칙을 쓴다. avoid에 든 문장은 건너뛴다 */
export function pickExpression(list: readonly string[], seed: number, avoid: readonly string[] = []): string {
  const start = seed % list.length;
  for (let i = 0; i < list.length; i++) {
    const s = list[(start + i) % list.length]!;
    if (!avoid.includes(s)) return s;
  }
  return list[start]!;
}
