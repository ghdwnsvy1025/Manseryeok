/** 이 글자가 오늘 이 사람에게 작용하는 방식 한 줄. 유형을 모르거나(옛 캐시) 시간 모름으로 불확실하거나 용신이 없으면 null */
export function typeNoteOf(core: CoreFortune, p: CoreLuckPart): string | null {
  const kind = core.chartType?.신강약;
  if (!kind || p.label === null || (core.dayLuck.agreement ?? 1) < MIN_TYPE_AGREEMENT) return null;
  // "원국 식상과 운 관성이 대립"은 글자 표시가 없지만 신약의 관성 글자에만 붙는다
  const flags = core.relations.flags.filter((f) => p.family === "관성" || !f.startsWith("원국 식상과"));
  const special = SPECIAL_NOTE.find((s) => flags.some((f) => s.match(f, p.char)));
  return special?.note ?? TYPE_NOTE[kind][p.family]?.[p.label] ?? null;
}
